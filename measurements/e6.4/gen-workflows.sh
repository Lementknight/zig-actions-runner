#!/bin/sh
# The workload for claim E6.4: a warm `uv sync` of pallets/flask, on this runner and on a hosted
# one. Two workflows, identical but for `runs-on`, so the only difference between the arms is the
# machine.
#
#   gen-workflows.sh <outdir>
#
# Two things about the method, both deliberate departures from how the study took this number.
#
# **The measured sync is warmed inside its own job.** The study compared a re-run here against a
# re-run on a hosted runner, which is not the same quantity on the two machines: this runner keeps
# the project environment in uv's cache volume so a re-run reconciles an environment that is already
# correct, while a hosted runner's workspace is new every job, so its "re-run" rebuilds `.venv` by
# hardlinking from a warm cache. One is a no-op and the other is work. A `warm` step before the
# measured one makes both arms measure the same thing — reconciling an environment that is already
# there — which is what "a warm `uv sync`" has to mean if the two numbers are to be compared at all.
#
# **Both steps carry the trial's token**, so neither can be served from the step cache (the token is
# in the script text, which is part of the key). Without it this runner's arm would measure a replay,
# which is not a sync at all. The hosted arm has no step cache and ignores the token.
set -eu
out=${1:?outdir}
mkdir -p "$out"

# flask at a pinned commit, with the uv.lock that `uv sync` reads (279 KB, 84 packages in the study).
ref=d086db856be187255b8ec61ef409357393020f32

emit() { # $1 = arm name, $2 = the `runs-on` value
	cat <<EOF
# Generated by measurements/e6.4/gen-workflows.sh — do not edit by hand.
name: measure-uv-$1
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
  sync:
    runs-on: $2
    steps:
      - uses: actions/checkout@v4
        with:
          repository: pallets/flask
          ref: $ref
      - uses: astral-sh/setup-uv@v6
        with:
          # The hosted arm needs this to have a warm uv cache at all; this runner provides one per
          # repository itself, and restoring GitHub's on top of it is harmless.
          enable-cache: true
      - name: warm
        run: |
          : "trial \${{ inputs.token }}"
          uv sync
      - name: measured sync
        run: |
          : "trial \${{ inputs.token }}"
          s=\$(date +%s%N)
          uv sync
          e=\$(date +%s%N)
          # Milliseconds, because the API's step timings are whole seconds and the quantity here is
          # under a second. arm.sh turns this into the harness's \`MEASURE\` line.
          echo "MEASURE_MS \$(( (e - s) / 1000000 ))"
EOF
}

emit pi '[self-hosted, zig]' > "$out/measure-uv-pi.yml"
emit hosted 'ubuntu-latest' > "$out/measure-uv-hosted.yml"
echo "wrote $out/measure-uv-pi.yml and $out/measure-uv-hosted.yml" >&2
