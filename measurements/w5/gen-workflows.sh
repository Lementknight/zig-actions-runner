#!/bin/sh
# The workload for claim W.5: an editable install of sqlalchemy with its test dependencies, on this
# runner and on a hosted one. Two workflows, identical but for `runs-on`, so the only difference
# between the arms is the machine.
#
#   gen-workflows.sh <outdir>
#
# The method, and the one departure from how the study took this number. The study compared an
# install here, where uv's cache volume already held every wheel, against an install on a hosted
# runner, which downloaded them from PyPI — its own sentence in STUDY.md §2 says so. That is a
# comparison of cache states, not of machines, and it is the same defect that refuted E6.4.
#
# Here a `warm` step installs once and then **deletes the virtualenv**, so what survives into the
# measured step is uv's package cache and not the environment. The measured step therefore does a
# real install — create the venv, unpack, link, build the Cython extensions — with every wheel
# already local on both arms. See README.md for why that is the right symmetric quantity and why
# E6.4's kind of warm would have measured the wrong thing.
#
# Both steps carry the trial's token, which is in the script text and so in the step's cache key:
# without it this runner's arm would measure a replay rather than an install.
set -eu
out=${1:?outdir}
mkdir -p "$out"

# sqlalchemy pinned, so the dependency set cannot move under a series of trials.
ref=7b95e267c867f9e35ee0aba7e637f373522b0e1d

# The test dependencies sqlalchemy's own tox.ini lists, plus the asyncio extra. The study recorded
# "editable with test deps" and not the command, so this defines the phrase rather than reproducing
# it; both arms run this identical line, which is what the comparison needs.
deps='-e ".[asyncio]" "pytest>=7.0.0rc1,<10" pytest-xdist "greenlet>=1" "typing-extensions>=4.13.0rc1"'

emit() { # $1 = arm name, $2 = the `runs-on` value
	cat <<EOF
# Generated by measurements/w5/gen-workflows.sh — do not edit by hand.
name: measure-install-$1
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
  install:
    runs-on: $2
    steps:
      - uses: actions/checkout@v4
        with:
          repository: sqlalchemy/sqlalchemy
          ref: $ref
      - uses: astral-sh/setup-uv@v6
        with:
          # The hosted arm needs this to have a warm uv cache at all; this runner provides one per
          # repository itself, and restoring GitHub's on top of it is harmless.
          enable-cache: true
      - name: warm
        run: |
          : "trial \${{ inputs.token }}"
          uv venv
          uv pip install $deps
          # The environment goes; the package cache stays. This is what makes the two arms install
          # the same thing — see README.md.
          #
          # Delete what \`.venv\` *points at*, not \`.venv\` itself. On this runner \`.venv\` is a
          # symlink into uv's cache volume (uv_env_in_cache, dagger.zig), so \`rm -rf .venv\` removes
          # the link and leaves the environment — after which the measured step's \`uv venv\` has
          # nowhere to put one and the install fails with "No virtual environment found". Removing
          # the target instead leaves a dangling link that \`uv venv\` refills, which is also what
          # happens on a job's first use. On a hosted runner \`.venv\` is a real directory, readlink
          # fails, and this removes \`.venv\`.
          rm -rf "\$(readlink .venv 2>/dev/null || echo .venv)"
      - name: measured install
        run: |
          : "trial \${{ inputs.token }}"
          s=\$(date +%s%N)
          uv venv
          uv pip install $deps
          e=\$(date +%s%N)
          # Milliseconds, because the API's step timings are whole seconds. arm.sh turns this into
          # the harness's \`MEASURE\` line.
          echo "MEASURE_MS \$(( (e - s) / 1000000 ))"
      - name: what was installed
        run: |
          : "trial \${{ inputs.token }}"
          # Recorded so a reading can be checked for having done the work: a cache state that
          # skipped the build would show here as a different package count.
          echo "PACKAGES \$(uv pip list | wc -l)"
EOF
}

emit pi '[self-hosted, zig]' > "$out/measure-install-pi.yml"
emit hosted 'ubuntu-latest' > "$out/measure-install-hosted.yml"
echo "wrote $out/measure-install-pi.yml and $out/measure-install-hosted.yml" >&2
