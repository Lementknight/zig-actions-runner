#!/bin/sh
# The workload for claim S.1: three concurrent jobs, each doing an unavoidably I/O-heavy install.
#
#   gen-workflow.sh > measure-io.yml
#
# `UV_LINK_MODE=copy` is the whole point. uv normally hardlinks package files out of its cache, which
# is nearly free; forced to copy, it writes flask's 214 MB environment file by file (the study
# measured 25.4 s for exactly this, docs/STUDY.md §10). Three shards at once is therefore about 640 MB
# of small-file writes and reads competing for one disk — the regime the SD card measurement says
# this machine cannot schedule its way out of (2,375 read iops, 702 write iops, and 39% more
# throughput for 15× the latency at queue depth 16; measurements/storage/README.md).
#
# `UV_PROJECT_ENVIRONMENT` is per shard *and* per trial, inside the workspace, so no shard reuses
# another's environment and no trial reuses an earlier one's. The workspace lives in the job's
# container, so nothing accumulates on disk between trials.
#
# The token is in the step's script text, which is part of its cache key, so no step is replayed and
# every trial does the work.
set -eu
ref=d086db856be187255b8ec61ef409357393020f32
cat <<EOF
# Generated by measurements/concurrency/gen-workflow.sh — do not edit by hand.
name: measure-io
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
  io:
    strategy:
      fail-fast: false
      matrix:
        shard: [1, 2, 3]
    runs-on: [self-hosted, zig]
    steps:
      - uses: actions/checkout@v4
        with:
          repository: pallets/flask
          ref: $ref
      - uses: astral-sh/setup-uv@v6
        with:
          enable-cache: true
      - name: copy-install
        env:
          # Defeats the hardlink path on purpose: this measures the disk, not uv.
          UV_LINK_MODE: copy
        run: |
          : "trial \${{ inputs.token }} shard \${{ matrix.shard }}"
          export UV_PROJECT_ENVIRONMENT="\$GITHUB_WORKSPACE/.venv-\${{ inputs.token }}-\${{ matrix.shard }}"
          # Timed in the step, in milliseconds. The first version of this claim read the batch's
          # makespan off the API instead, whose step and job timings are whole seconds, and whose
          # span also contains however long the third job sat queued — so the baseline arm varied
          # 64-81 s and no effect could be seen through it. This measures only the contended work.
          s=\$(date +%s%N)
          uv sync
          e=\$(date +%s%N)
          echo "MEASURE_MS \$(( (e - s) / 1000000 ))"
          du -sh "\$UV_PROJECT_ENVIRONMENT" || true
EOF
