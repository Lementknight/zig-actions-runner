#!/bin/sh
# The workloads for S.2 and S.3: how much does running jobs at once cost, and does the answer
# depend on whether the work is I/O-bound or CPU-bound?
#
#   gen-workflows.sh <outdir>
#
# Six files: two workloads × three levels of concurrency.
#
# **Concurrency is set with `max-parallel`, not with `RUNNER_COUNT`.** A three-shard matrix limited
# to one, two or three at a time is scheduled by GitHub, so the arms differ without the machine
# being reconfigured. S.1's first design restarted the service for every trial, which is why its
# trials went from two minutes alone to thirty-five back to back: the stop waits for running jobs,
# the pool must re-register, and under load 11 everything around that crawls. Nothing here touches
# the unit file, so there is no restore step and no sudo.
#
# `max-parallel` is a literal in each file rather than an expression, so the repository's own
# workflow checker can validate it and there is no question of where expressions are allowed.
#
# Both workloads do the same amount of work per shard, so the comparable quantity is **one shard's
# duration**: how long the work takes when one, two or three of them run at once. The sum is not
# comparable when the arms run different numbers of shards concurrently.
set -eu
out=${1:?outdir}
mkdir -p "$out"
ref=d086db856be187255b8ec61ef409357393020f32

emit() { # $1 = name, $2 = max-parallel, $3 = the timed step's body (indented 10 spaces)
	cat <<EOF
# Generated by measurements/concurrency/gen-workflows.sh — do not edit by hand.
name: $1
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
  work:
    strategy:
      fail-fast: false
      max-parallel: $2
      matrix:
        shard: [1, 2, 3]
    runs-on: [self-hosted, zig]
    steps:
      - uses: actions/checkout@v4
        with:
          repository: pallets/flask
          ref: $ref
      - uses: astral-sh/setup-uv@v6
        with:
          enable-cache: true
$3
EOF
}

# I/O-bound: uv forced to copy flask's 214 MB environment file by file instead of hardlinking it
# (25.4 s uncontended in docs/STUDY.md §10). This is the workload S.1 used, and it saturates the
# disk on purpose — which is exactly why its result cannot be generalised without the CPU-bound arm
# below.
io_step() {
	cat <<'EOF'
      - name: timed
        env:
          UV_LINK_MODE: copy
        run: |
          : "trial ${{ inputs.token }} shard ${{ matrix.shard }}"
          export UV_PROJECT_ENVIRONMENT="$GITHUB_WORKSPACE/.venv-${{ inputs.token }}-${{ matrix.shard }}"
          s=$(date +%s%N)
          uv sync
          e=$(date +%s%N)
          echo "MEASURE_MS $(( (e - s) / 1000000 ))"
EOF
}

# CPU-bound: flask's own test suite. The environment is built first, untimed and hardlinked, so the
# timed command is compute and not copying. This is the arm that decides whether S.1's finding
# describes real CI or only the adversarial case it was measured on.
cpu_step() {
	cat <<'EOF'
      - name: timed
        run: |
          : "trial ${{ inputs.token }} shard ${{ matrix.shard }}"
          export UV_PROJECT_ENVIRONMENT="$GITHUB_WORKSPACE/.venv-${{ inputs.token }}-${{ matrix.shard }}"
          # `tests`, not `dev`: flask's dev group is ruff and tox, and pytest is in `tests`.
          uv sync --group tests
          s=$(date +%s%N)
          uv run pytest -q --no-header -p no:cacheprovider
          e=$(date +%s%N)
          echo "MEASURE_MS $(( (e - s) / 1000000 ))"
EOF
}

for p in 1 2 3; do
	emit "measure-io-p$p" "$p" "$(io_step)" > "$out/measure-io-p$p.yml"
	emit "measure-cpu-p$p" "$p" "$(cpu_step)" > "$out/measure-cpu-p$p.yml"
done
echo "wrote six workflows to $out" >&2
