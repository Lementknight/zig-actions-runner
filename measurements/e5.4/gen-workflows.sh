#!/bin/sh
# The workload for claim E5.4: what `withDirectory` with `owner:` costs when the directory is new.
#
#   gen-workflows.sh <outdir>
#
# It writes a .github/ tree — two workflows and two local Dockerfile actions — to be copied into the
# test repository.
#
# `owner:` is emitted by exactly one condition in the runner (dagger.zig:4291): the Docker action's
# image declares a non-root user. So the two arms run the same action against the same workspace and
# differ only in a `USER` line in the Dockerfile. Both images are built from the same base with the
# same entrypoint, so the runner emits `owner:` for one and not the other and nothing else differs.
#
# The workspace is rebuilt every trial, with the trial's token in **every** file. One token would be
# enough to change the directory's digest and so defeat the step cache, but it would leave the other
# 19,999 blobs in the engine and the copy would be cheap for a reason unrelated to `owner:`. The
# study's probe reused one source directory, which is precisely the mistake being corrected.
set -eu
out=${1:?outdir}
mkdir -p "$out/.github/workflows" "$out/.github/actions/owner-probe-root" "$out/.github/actions/owner-probe-user"

files=20000
bytes=11000 # 20,000 x 11 KB is about 220 MB, the study's 200-240 MB

# The two actions. Identical but for the USER line; busybox because the image's own size must not be
# part of what is measured.
for arm in root user; do
	d="$out/.github/actions/owner-probe-$arm"
	cat > "$d/action.yml" <<EOF
# Generated by measurements/e5.4/gen-workflows.sh — do not edit by hand.
name: owner probe ($arm)
description: Receives the workspace, as a Docker action does. The $arm image's user decides whether the runner emits owner:.
runs:
  using: docker
  image: Dockerfile
EOF
	{
		echo "# Generated by measurements/e5.4/gen-workflows.sh — do not edit by hand."
		echo "FROM busybox:1.37"
		if [ "$arm" = user ]; then echo "USER 1001"; fi
		# Counts what it was given, so a trial that received the wrong workspace is visible in the
		# log rather than silently fast. `id -u` records which user the action ran as, which is the
		# condition the whole experiment turns on.
		# shellcheck disable=SC2016 # the $(...) must reach the Dockerfile unexpanded
		echo 'ENTRYPOINT ["sh","-c","echo PROBE_USER $(id -u); echo PROBE_FILES $(find /github/workspace/big -type f | wc -l)"]'
	} > "$d/Dockerfile"
done

emit() { # $1 = arm name
	cat <<EOF
# Generated by measurements/e5.4/gen-workflows.sh — do not edit by hand.
name: measure-owner-$1
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
  owner:
    runs-on: [self-hosted, zig]
    steps:
      - uses: actions/checkout@v4
      - name: build a new workspace
        run: |
          : "trial \${{ inputs.token }}"
          rm -rf big
          mkdir big
          # printf is a shell builtin, so this is $files writes and not $files process spawns —
          # which matters on this machine, where the SD card is already the bottleneck.
          block=\$(head -c $bytes /dev/zero | tr '\\0' 'x')
          i=0
          while [ \$i -lt $files ]; do
            printf '%s%s' "\${{ inputs.token }}" "\$block" > "big/f\$i"
            i=\$((i + 1))
          done
          echo "WORKSPACE_BYTES \$(du -sm big | cut -f1) MB in \$(find big -type f | wc -l) files"
      - name: measured
        # The quantity. What is timed happens while the action's container is being built — the
        # workspace being copied in, with or without an ownership pass — so it cannot be clocked
        # from inside the step. arm.sh reads this step's duration from the API.
        uses: ./.github/actions/owner-probe-$1
EOF
}

emit root > "$out/.github/workflows/measure-owner-root.yml"
emit user > "$out/.github/workflows/measure-owner-user.yml"
echo "wrote $out/.github/ with 2 workflows and 2 actions" >&2
