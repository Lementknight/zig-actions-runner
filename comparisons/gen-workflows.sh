#!/bin/sh
# Feature-parity comparisons: one workflow per feature, with the *same* job defined twice — once on
# `ubuntu-latest` and once on `[self-hosted, zig]` — so GitHub's runner and ours answer the same
# input and the two logs can be read side by side.
#
# This is the technique the project uses whenever "does ours behave like GitHub's?" is the question,
# and it is worth generating rather than hand-installing: a comparison is only evidence if both arms
# are known to be identical, which a single `emit` guarantees and two edited files do not.
#
#   gen-workflows.sh <outdir>
#
# Install the output in the test repository (see docs/DEPLOY.md, "The test repository"), start a
# runner scoped to it, and dispatch with a token that is new every trial so no step is replayed:
#
#   gh workflow run shell-python.yml -R "$repo" -f "token=$(date +%s)"
#
# Then compare the two jobs of that run. What to look for is in each emitter below.
set -eu
out=${1:?outdir}
mkdir -p "$out"

# $1 = workflow name, $2 = the steps of the job, indented six spaces, with `${{ }}` escaped.
emit() {
	name=$1
	steps=$2
	for arm in 'ubuntu-latest' '[self-hosted, zig]'; do
		case $arm in
		ubuntu-latest) job=hosted ;;
		*) job=selfhosted ;;
		esac
		if [ "$job" = hosted ]; then
			cat <<EOF
# Generated by comparisons/gen-workflows.sh — do not edit by hand.
name: $name
on:
  workflow_dispatch:
    inputs:
      token:
        description: A value new for every trial, so no step can be replayed
        required: true
jobs:
EOF
		fi
		printf '  %s:\n    runs-on: %s\n    steps:\n%s\n' "$job" "$arm" "$steps"
	done
}

# `shell: python`. The three things worth reading are all in the log, not the exit status: the
# `shell:` line of the group header (GitHub expands a bare `python` to `/usr/bin/python`, and so do
# we), the interpreter version, and `sys.argv[0]` — whose `.py` extension is the reason
# `scriptPath` varies with the shell, since that name reaches a traceback. SPEC §6.
python_steps=$(
	cat <<'EOF'
      - name: python ok
        shell: python
        run: |
          import sys, platform
          print("trial ${{ inputs.token }}")
          print("python", platform.python_version())
          print("argv0", sys.argv[0])
EOF
)
emit shell-python "$python_steps" > "$out/shell-python.yml"

# Problem matchers. A matcher is registered in one step and the diagnostics come from a later one,
# which is both the realistic shape (`setup-node` registers tsc's matcher; the compiler runs after)
# and the only shape the two runners agree on: ours applies a matcher from the *next* step, so a
# comparison that emitted diagnostics in the registering step would show a real divergence rather
# than test one. SPEC §9 records it.
#
# Read the run's annotations, not the log. Expect the same levels, lines, columns and messages from
# both arms, and two differences in ours: it reports the path the matcher captured where GitHub
# falls back to the workflow file (those source files do not exist in the checked-out repository),
# and it keeps the matcher's `code` as the annotation title, which GitHub drops. The third line
# matches nothing and must produce no annotation on either.
matcher_steps=$(
	cat <<'EOF'
      - uses: actions/checkout@v4
        with:
          repository: go-chi/chi
          ref: 3a33ba578e0dd93444e0ff386cc26e665d92e31e
      - name: register and emit
        run: |
          : "trial ${{ inputs.token }}"
          cat > /tmp/m.json <<'JSON'
          { "problemMatcher": [ { "owner": "zig-check", "pattern": [
            { "regexp": "^([^\\s].*)\\((\\d+),(\\d+)\\): (error|warning) ZC(\\d+): (.*)$",
              "file": 1, "line": 2, "column": 3, "severity": 4, "code": 5, "message": 6 } ] } ] }
          JSON
          echo "::add-matcher::/tmp/m.json"
      - name: produce diagnostics
        run: |
          : "trial ${{ inputs.token }}"
          echo "src/alpha.ts(12,5): error ZC2304: Cannot find name 'alpha'."
          echo "src/beta.ts(7,19): warning ZC6133: 'beta' is declared but never read."
          echo "not a diagnostic line"
EOF
)
emit matcher-check "$matcher_steps" > "$out/matcher-check.yml"

# `fromPath`, which is the one matcher property with no real action shipping it that this runner
# would meet — .NET's matcher is its canonical user, and .NET is a non-goal. That makes a comparison
# *more* valuable rather than less: the implementation was written from the specification, so the
# only way to know it resolves paths the way GitHub does is to ask GitHub.
#
# The files have to exist in the repository. GitHub's annotation payload falls back to the workflow
# file for a path that is not in the commit — which is why the comparison above shows `.github` on
# the hosted side — so a probe tree is written here and committed with the workflows. Without it
# both arms would report a fallback and the comparison would show nothing.
mkdir -p "$out/probe/app/sub" "$out/probe/shared"
echo "a project file; the matcher captures this path with fromPath" > "$out/probe/app/app.proj"
for f in probe/app/Program.cs probe/app/sub/Other.cs probe/shared/Util.cs; do
	echo "// a file the matcher must resolve to: $f" > "$out/$f"
done

frompath_steps=$(
	cat <<'EOF'
      - uses: actions/checkout@v4
      - name: register a matcher that uses fromPath
        run: |
          : "trial ${{ inputs.token }}"
          cat > /tmp/fp.json <<'JSON'
          { "problemMatcher": [ { "owner": "proj-probe", "pattern": [
            { "regexp": "^Building (.+\.proj)$", "fromPath": 1 },
            { "regexp": "^(.+)\((\d+),(\d+)\): (error|warning) ([A-Z]+\d+): (.*)$",
              "file": 1, "line": 2, "column": 3, "severity": 4, "code": 5, "message": 6,
              "loop": true } ] } ] }
          JSON
          echo "::add-matcher::/tmp/fp.json"
      - name: diagnostics with paths relative to the project file
        run: |
          : "trial ${{ inputs.token }}"
          # Each path below is relative to probe/app/, not to the workspace. Resolved correctly all
          # three name a file that exists; resolved wrongly they name nothing.
          echo "Building probe/app/app.proj"
          echo "Program.cs(12,5): error PP0001: resolves to probe/app/Program.cs"
          echo "sub/Other.cs(3,1): warning PP0002: resolves to probe/app/sub/Other.cs"
          echo "../shared/Util.cs(7,2): error PP0003: dot-dot, resolves to probe/shared/Util.cs"
EOF
)
emit matcher-frompath "$frompath_steps" > "$out/matcher-frompath.yml"

echo "wrote $out/shell-python.yml, $out/matcher-check.yml, $out/matcher-frompath.yml and $out/probe/" >&2
